_TEMPLATE_DIR = Path(__file__).parent / 'templates'


class HtmlTemplate(Template):
    """Template subclass using %{var} delimiter to avoid CSS/JS conflicts."""
    delimiter = '%'


def _load_template(name: str) -> str:
    """Load a template file from the templates directory."""
    path = _TEMPLATE_DIR / name
    with open(path, 'r', encoding='utf-8') as f:
        return f.read()


def generate_report(results: dict, output_path: str) -> None:
    """Generate a self-contained HTML report file.

    Args:
        results: Dict with keys: metadata, cells_summary, assumptions,
                 hardcodes, kpis, flow_blocks, graph_stats, cells, pro_forma
        output_path: Path to write the HTML file
    """
    sections = [
        _build_nav(results.get("graph_stats", {})),
        _build_summary(results),
        _build_flow(results.get("flow_blocks", [])),
        _build_assumptions(results.get("assumptions", [])),
        _build_proforma(results.get("pro_forma", {}), results.get("cells", {})),
        _build_hardcodes(results.get("hardcodes", [])),
        _build_kpis(results.get("kpis", [])),
        _build_complexity(results.get("complexity", {})),
        _build_dependencies(results.get("graph_stats", {}), results.get("graph_json", "{}"), results.get("kpis", [])),
        _build_circular_refs(results.get("graph_stats", {})),
        _build_cells_inventory(results.get("cells", {}), results.get("cells_summary", {})),
        _build_parser_warnings(results.get("graph_stats", {})),
    ]

    css = _load_template('report.css')
    title = _esc((results.get('metadata', {}).get('display_name') or results.get('metadata', {}).get('model_name', 'Model Analysis')))
    body = ''.join(sections)

    # Load interactive JS
    sort_js = _load_template('sort.js')
    collapse_js = _load_template('collapse.js')
    explorer_js = _load_template('explorer.js')
    app_js = sort_js + '\n' + collapse_js + '\n' + explorer_js

    # Print header/footer
    generated_date = datetime.now().strftime('%Y-%m-%d %H:%M')
    print_header = (
        '<div class="print-header">'
        f'<span>{title}</span>'
        '<span style="float:right">Generated by xlens</span>'
        '</div>'
    )
    print_footer = (
        f'<div class="print-footer">Report generated {generated_date}</div>'
    )

    tpl = HtmlTemplate(_load_template('base.html'))
    page = tpl.substitute(
        title=title,
        css=css,
        app_js=app_js,
        body=body,
        print_header=print_header,
        print_footer=print_footer,
    )

    with open(output_path, "w", encoding="utf-8") as f:
        f.write(page)


def _script_safe_json(text: str) -> str:
    """Make a JSON string safe to place inside a <script> element.

    '<' only occurs inside JSON strings, where \\u003c decodes back to '<', so the data is
    unchanged but nothing can end the script element or open an HTML comment.
    """
    return (text.replace('<', '\\u003c').replace('>', '\\u003e')
            .replace('\u2028', '\\u2028').replace('\u2029', '\\u2029'))


def _esc(text) -> str:
    """HTML-escape a value."""
    if text is None:
        return ""
    return html_module.escape(str(text))


def _fmt_num(val, fmt_type="currency") -> str:
    """Format a numeric value for display."""
    if val is None:
        return "N/A"
    if isinstance(val, str):
        return _esc(val)
    if not isinstance(val, (int, float)):
        return _esc(str(val))

    if fmt_type == "pct":
        return f"{val:.1%}"
    if fmt_type == "ratio":
        return f"{val:.2f}x"
    if fmt_type == "int":
        return f"{val:,.0f}"
    # currency
    if abs(val) >= 1:
        return f"${val:,.0f}"
    return f"{val:,.4f}"




