def _build_dependencies(stats: dict, graph_json: str = "{}", kpis: list = None) -> str:
    hub_rows = ""
    for node_id, degree in stats.get("hub_nodes", []):
        hub_rows += f"<tr><td style='font-family:monospace;font-size:0.78rem'>{_esc(node_id)}</td><td style='text-align:center'>{degree}</td></tr>"

    root_rows = ""
    for node_id in stats.get("root_nodes", [])[:10]:
        root_rows += f"<tr><td style='font-family:monospace;font-size:0.78rem'>{_esc(node_id)}</td></tr>"

    terminal_rows = ""
    for node_id in stats.get("terminal_nodes", [])[:10]:
        terminal_rows += f"<tr><td style='font-family:monospace;font-size:0.78rem'>{_esc(node_id)}</td></tr>"

    # Escape every '<' (not just '</script>'): HTML end-tag matching is case-insensitive
    # and '<!--' can also break out, and labels/sheet names come from untrusted workbooks.
    safe_graph_json = _script_safe_json(graph_json)
    kpi_refs = [
        {"cell": k.get("cell_ref", ""), "name": k.get("name", "")}
        for k in (kpis or []) if k.get("cell_ref")
    ]
    safe_kpi_json = _script_safe_json(json.dumps(kpi_refs))

    return f"""
<section id="dependencies">
<details open>
<summary>Dependency Explorer</summary>
<div class="card-grid" style="grid-template-columns: repeat(3, 1fr);">
  <div class="card stat-card"><div class="num">{stats.get('total_nodes',0)}</div><div class="lbl">Graph Nodes</div></div>
  <div class="card stat-card"><div class="num">{stats.get('total_edges',0)}</div><div class="lbl">Edges</div></div>
  <div class="card stat-card"><div class="num">{stats.get('root_count',0)}</div><div class="lbl">Root Inputs</div></div>
</div>

<!-- Row map + Trace explorer (templates/explorer.js) -->
<div class="card xe-section">
  <script type="application/json" id="xe-kpis">{safe_kpi_json}</script>
  <div id="xe-root"><p class="xe-muted">Loading the dependency explorer…</p></div>
</div>


<script>
const graphData = {safe_graph_json};
</script>

<h3>Top Hub Nodes (Most Referenced)</h3>
<div class="table-wrap"><table><thead><tr><th>Cell</th><th style="text-align:center">Out-Degree</th></tr></thead><tbody>{hub_rows}</tbody></table></div>

<h3>Root Nodes (Pure Inputs)</h3>
<div class="table-wrap"><table><thead><tr><th>Cell</th></tr></thead><tbody>{root_rows}</tbody></table></div>

<h3>Terminal Nodes (Outputs)</h3>
<div class="table-wrap"><table><thead><tr><th>Cell</th></tr></thead><tbody>{terminal_rows}</tbody></table></div>
</details>
</section>
"""


def _build_circular_refs(graph_stats: dict) -> str:
    """Build the Circular References report section."""
    if not graph_stats.get("has_circular_refs", False):
        return ""

    cycles = graph_stats.get("circular_references", [])
    count = graph_stats.get("circular_ref_count", len(cycles))

    rows = ""
    for i, cycle_info in enumerate(cycles, 1):
        cycle_cells = cycle_info.get("cycle", [])
        length = cycle_info.get("length", len(cycle_cells))
        # Format as chain: A -> B -> C -> (back to start)
        chain = " &rarr; ".join(_esc(c) for c in cycle_cells)
        if cycle_cells:
            chain += f" &rarr; {_esc(cycle_cells[0])}"
        rows += f"<tr><td style='text-align:center'>{i}</td><td style='text-align:center'>{length}</td><td style='font-family:monospace;font-size:0.78rem'>{chain}</td></tr>"

    note = ""
    if count > 100:
        note = f"<p style='color:var(--text-muted);font-size:0.82rem;margin-top:0.5rem;'>Showing first 100 of {count}+ detected chains</p>"

    return f"""
<section id="circular-refs">
<details open>
<summary style="color:var(--accent-red);">Circular References</summary>
<div class="card">
  <p><strong>{count} circular reference chain{'s' if count != 1 else ''} detected</strong></p>
  <div class="table-wrap">
    <table>
      <thead><tr><th style="width:60px">Chain #</th><th style="width:60px">Length</th><th>Cells Involved</th></tr></thead>
      <tbody>
      {rows}
      </tbody>
    </table>
  </div>
  {note}
</div>
</details>
</section>
"""


def _build_parser_warnings(graph_stats: dict) -> str:
    """Build the Parser Notes report section."""
    warnings = graph_stats.get("parser_warnings", [])
    if not warnings:
        return ""

    items = "".join(f"<li>{_esc(w)}</li>" for w in warnings)

    return f"""
<section id="parser-notes">
<details>
<summary>Parser Notes</summary>
<div class="card" style="border-left:3px solid var(--accent-amber);">
  <p style="font-weight:600;">{len(warnings)} parser note{'s' if len(warnings) != 1 else ''}</p>
  <ul style="margin-top:0.5rem;font-size:0.82rem;color:var(--text-muted);">
    {items}
  </ul>
</div>
</details>
</section>
"""


def _build_cells_inventory(cells: dict, cells_summary: dict) -> str:
    # Classification distribution bar chart
    dist = cells_summary.get("classification_dist", {})
    max_count = max(dist.values()) if dist else 1
    colors = {
        "derived": "var(--accent-blue)",
        "deal_input": "var(--accent-green)",
        "structural_assumption": "var(--accent-purple)",
        "hardcoded_in_cashflow": "var(--accent-amber)",
        "metadata": "#6c757d",
        "label": "#adb5bd",
    }

    bars = ""
    for cls, count in sorted(dist.items(), key=lambda x: -x[1]):
        width = max(2, int(count / max_count * 300))
        color = colors.get(cls, "#6c757d")
        bars += f"""<div class="bar-row">
  <div class="bar-label">{_esc(cls)}</div>
  <div class="bar" style="width:{width}px;background:{color}"></div>
  <div class="bar-count">{count}</div>
</div>"""

    # Group cells by sheet
    sheets = {}
    for (sheet, _coord), cell_data in cells.items():
        sheets.setdefault(sheet, []).append(cell_data)

    sheet_sections = ""
    for sheet_name, sheet_cells in sheets.items():
        sheet_cells.sort(key=lambda c: (c["row"], c["col"]))
        rows_html = ""
        for cd in sheet_cells:
            cls = cd.get("classification", "")
            badge_cls = {
                "derived": "badge-blue",
                "deal_input": "badge-green",
                "structural_assumption": "badge-purple",
                "hardcoded_in_cashflow": "badge-amber",
                "metadata": "",
                "label": "",
            }.get(cls, "")

            formula = cd.get("formula") or cd.get("raw_value") or ""
            cached = cd.get("cached_value", "")

            rows_html += f"""<tr>
  <td style="font-family:monospace;font-size:0.78rem">{_esc(cd['cell_ref'])}</td>
  <td><span class="badge {badge_cls}">{_esc(cls)}</span></td>
  <td style="font-size:0.78rem;max-width:300px;overflow:hidden;text-overflow:ellipsis">{_esc(str(formula)[:80])}</td>
  <td style="font-size:0.78rem">{_esc(str(cached)[:40]) if cached is not None else ''}</td>
</tr>"""

        sheet_sections += f"""
<details>
<summary>{_esc(sheet_name)} ({len(sheet_cells)} cells)</summary>
<div class="table-wrap">
<table>
<thead><tr><th class="sortable">Cell</th><th class="sortable">Classification</th><th class="sortable">Formula/Value</th><th class="sortable">Cached Value</th></tr></thead>
<tbody>
{rows_html}
</tbody>
</table>
</div>
</details>"""

    return f"""
<section id="cells">
<details>
<summary>Cell Inventory</summary>
<h3>Classification Distribution</h3>
<div class="bar-chart">{bars}</div>
{sheet_sections}
</details>
</section>
</div><!-- close container -->
"""
