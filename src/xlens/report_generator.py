def _build_nav(graph_stats: dict = None) -> str:
    if graph_stats is None:
        graph_stats = {}
    links = [
        ("summary", "Summary"),
        ("flow", "Model Flow"),
        ("assumptions", "Assumptions"),
        ("proforma", "Main schedule"),
        ("hardcodes", "Hardcodes"),
        ("kpis", "KPIs"),
        ("complexity", "Complexity"),
        ("dependencies", "Dependencies"),
    ]
    if graph_stats.get("has_circular_refs", False):
        links.append(("circular-refs", "Circular Refs"))
    links.append(("cells", "Cells"))
    if graph_stats.get("parser_warnings", []):
        links.append(("parser-notes", "Parser Notes"))
    items = ''.join(f'<a href="#{id}">{label}</a>' for id, label in links)
    return f'<div class="nav"><span class="brand">Xlens</span>{items}<button id="toggle-all" class="no-print">Collapse All</button></div>'


def _build_summary(results: dict) -> str:
    meta = results.get("metadata", {})
    cs = results.get("cells_summary", {})
    assumptions = results.get("assumptions", [])
    kpis = results.get("kpis", [])
    hardcodes = results.get("hardcodes", [])

    model_name = _esc(meta.get("display_name") or meta.get("model_name", "Unknown"))
    prop_name = _esc(meta.get("property_name", ""))
    date = _esc(meta.get("date_analyzed", ""))
    sheet_count = meta.get("sheet_count", 0)
    cell_count = cs.get("total", 0)
    formula_count = cs.get("formula_count", 0)

    warning_count = sum(1 for h in hardcodes if h.get("severity") in ("warning", "error"))
    if warning_count <= 2:
        health_cls, health_txt = "health-green", "Healthy"
    elif warning_count <= 5:
        health_cls, health_txt = "health-yellow", "Minor Issues"
    else:
        health_cls, health_txt = "health-red", "Needs Review"

    return f"""
<div class="container">
<section id="summary">
<h2>Executive Summary</h2>
<div class="card">
  <h3>{model_name}</h3>
  <p>{prop_name} &mdash; Analyzed: {date}</p>
  <p>Health: <span class="{health_cls} health">{health_txt}</span> ({warning_count} warnings/errors)</p>
</div>
<div class="card-grid">
  <div class="card stat-card"><div class="num">{sheet_count}</div><div class="lbl">Sheets</div></div>
  <div class="card stat-card"><div class="num">{cell_count}</div><div class="lbl">Cells</div></div>
  <div class="card stat-card"><div class="num">{formula_count}</div><div class="lbl">Formulas</div></div>
  <div class="card stat-card"><div class="num">{len(assumptions)}</div><div class="lbl">Assumptions</div></div>
  <div class="card stat-card"><div class="num">{len(kpis)}</div><div class="lbl">KPIs</div></div>
  <div class="card stat-card"><div class="num">{len(hardcodes)}</div><div class="lbl">Hardcode Flags</div></div>
</div>
</section>
"""


def _build_flow(flow_blocks: list) -> str:
    cards = []
    for i, block in enumerate(flow_blocks):
        # Key formulas
        formulas_html = ""
        for kf in block.get("key_formulas", []):
            formulas_html += f'<span class="formula-code">{_esc(kf.get("readable", ""))}</span>'

        # Driving assumptions as tags
        tags = ''.join(
            f'<span class="flow-tag">{_esc(a)}</span>'
            for a in block.get("driving_assumptions", [])[:6]
        )

        # Connects-to
        connects = ", ".join(block.get("connects_to", [])) or "Terminal"

        cards.append(f"""
<div class="flow-card card">
  <h3>{_esc(block["name"])}</h3>
  <p>{_esc(block.get("description", ""))}</p>
  <p style="font-size:0.78rem;color:var(--text-muted)">{block.get("cell_count",0)} cells, {block.get("formula_count",0)} formulas &rarr; {_esc(connects)}</p>
  {formulas_html}
  <div class="flow-tags">{tags}</div>
</div>""")

        if i < len(flow_blocks) - 1:
            cards.append('<div class="flow-arrow">&#9660;</div>')

    return f"""
<section id="flow">
<details open>
<summary>Model Flow</summary>
<div class="flow-container">
{''.join(cards)}
</div>
</details>
</section>
"""


def _build_assumptions(assumptions: list) -> str:
    # Group by category
    groups = {}
    for a in assumptions:
        cat = a.get("category", "Other")
        groups.setdefault(cat, []).append(a)

    sections = []
    for cat in ["Property Details", "Acquisition", "Debt Terms", "Partnership", "Growth", "Exit", "Other"]:
        items = groups.get(cat, [])
        if not items:
            continue

        rows = ""
        for a in items:
            badge_cls = "badge-blue" if a.get("deal_specific") else "badge-green"
            badge_txt = "Deal-Specific" if a.get("deal_specific") else "Structural"
            val = a.get("value", "")
            if isinstance(val, float) and 0 < val < 1:
                val_str = f"{val:.1%}"
            elif isinstance(val, (int, float)):
                val_str = f"{val:,.0f}" if abs(val) >= 10 else f"{val}"
            else:
                val_str = _esc(str(val))

            rows += f"""<tr>
  <td>{_esc(a.get('name',''))}</td>
  <td style="font-family:monospace;font-size:0.78rem">{_esc(a.get('cell_ref',''))}</td>
  <td style="text-align:right;font-weight:600">{val_str}</td>
  <td><span class="badge {badge_cls}">{badge_txt}</span></td>
  <td style="text-align:center">{a.get('downstream_count', 0)}</td>
</tr>"""

        sections.append(f"""
<details{'open' if cat in ('Growth','Debt Terms') else ''}>
<summary>{_esc(cat)} ({len(items)})</summary>
<div class="table-wrap">
<table>
<thead><tr><th class="sortable">Name</th><th class="sortable">Cell</th><th class="sortable" style="text-align:right">Value</th><th class="sortable">Type</th><th class="sortable" style="text-align:center">Impact</th></tr></thead>
<tbody>
{rows}
</tbody>
</table>
</div>
</details>""")

    return f"""
<section id="assumptions">
<details>
<summary>Assumptions</summary>
{''.join(sections)}
</details>
</section>
"""


def _main_schedule_sheet(cells: dict):
    """Pick the calc sheet with the most formula cells (None if there is no formula sheet)."""
    counts: dict = {}
    for (sheet, _coord), cd in cells.items():
        if cd.get("sheet_role") == "calc" and cd.get("formula"):
            counts[sheet] = counts.get(sheet, 0) + 1
    if not counts:
        return None
    return max(counts, key=lambda s: (counts[s], s))


def _build_proforma(pro_forma: dict, cells: dict) -> str:
    """Render the main calculation sheet (most formulas) as an HTML table."""
    main_sheet = _main_schedule_sheet(cells)
    pf_cells = {}
    if main_sheet is not None:
        for (sheet, _coord), cell_data in cells.items():
            if sheet == main_sheet:
                pf_cells[(cell_data["row"], cell_data["col"])] = cell_data

    if not pf_cells:
        return '<section id="proforma"><details><summary>Main schedule</summary><p>No calculation sheet found.</p></details></section>'

    max_row = max(r for r, c in pf_cells)
    max_col = max(c for r, c in pf_cells)

    rows_html = []
    for row in range(1, max_row + 1):
        cells_html = []
        for col in range(1, max_col + 1):
            cd = pf_cells.get((row, col))
            if cd is None:
                cells_html.append("<td></td>")
                continue

            val = cd.get("cached_value")
            formula = cd.get("formula")
            cls = cd.get("classification", "")

            css_class = ""
            if formula:
                css_class = "pf-formula"
            elif cls == "hardcoded_in_cashflow":
                css_class = "pf-hardcoded"

            if val is None:
                display = ""
            elif isinstance(val, str):
                display = _esc(val)
            elif isinstance(val, (int, float)):
                if abs(val) >= 100:
                    display = f"{val:,.0f}"
                elif abs(val) < 1 and val != 0:
                    display = f"{val:.1%}"
                else:
                    display = f"{val:,.2f}"
            else:
                display = _esc(str(val))

            tag = "th" if row <= 3 or col == 1 else "td"
            cells_html.append(f'<{tag} class="{css_class}">{display}</{tag}>')

        rows_html.append(f"<tr>{''.join(cells_html)}</tr>")

    return f"""
<section id="proforma">
<details>
<summary>Main schedule: {_esc(main_sheet)}</summary>
<p style="font-size:0.78rem;color:var(--text-muted)">
  <span class="badge badge-blue">Blue</span> = formula &nbsp;
  <span class="badge badge-amber">Yellow</span> = hardcoded value
</p>
<div class="table-wrap">
<table class="pf-table">
{''.join(rows_html)}
</table>
</div>
</details>
</section>
"""


